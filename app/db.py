from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine
from app.config import DATABASE_URL
_engine = None

def engine() -> Engine:
    global _engine
    if _engine is None:
        kwargs={'pool_pre_ping':True}
        if DATABASE_URL.startswith('sqlite:'): kwargs={'connect_args':{'check_same_thread':False}}
        db_url = DATABASE_URL.replace('postgresql://', 'postgresql+psycopg://', 1)
        _engine = create_engine(db_url, **kwargs)
        with _engine.begin() as conn:
            conn.execute(text('''CREATE TABLE IF NOT EXISTS predictions (
                id TEXT PRIMARY KEY, conversation_id TEXT, message TEXT NOT NULL,
                intent TEXT NOT NULL, confidence REAL NOT NULL, model_version TEXT NOT NULL,
                handoff INTEGER NOT NULL DEFAULT 0, handoff_reason TEXT,
                llm_status TEXT NOT NULL DEFAULT 'pending', llm_response TEXT,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)'''))
            conn.execute(text('CREATE TABLE IF NOT EXISTS conversation_state (conversation_id TEXT PRIMARY KEY, failed_attempts INTEGER NOT NULL DEFAULT 0)'))

            if DATABASE_URL.startswith('sqlite:'):
                id_column = 'INTEGER PRIMARY KEY AUTOINCREMENT'
            else:
                id_column = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'

            conn.execute(text(f'''CREATE TABLE IF NOT EXISTS conversation_messages (
                id {id_column},
                conversation_id TEXT NOT NULL,
                message TEXT NOT NULL,
                intent TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)'''))
    return _engine


def save_prediction(row: dict):
    with engine().begin() as conn:
        conn.execute(text('''INSERT INTO predictions
        (id,conversation_id,message,intent,confidence,model_version,handoff,handoff_reason,llm_status,llm_response)
        VALUES (:id,:conversation_id,:message,:intent,:confidence,:model_version,:handoff,:handoff_reason,:llm_status,:llm_response)'''),row)

def update_llm(prediction_id: str,status: str,response: str|None):
    with engine().begin() as conn:
        conn.execute(text('UPDATE predictions SET llm_status=:s,llm_response=:r WHERE id=:id'),{'s':status,'r':response,'id':prediction_id})

def get_prediction(prediction_id: str):
    with engine().begin() as conn:
        row=conn.execute(text('SELECT * FROM predictions WHERE id=:id'),{'id':prediction_id}).mappings().first()
        return dict(row) if row else None

def dashboard_data():
    with engine().begin() as conn:
        total=conn.execute(text('SELECT COUNT(*) FROM predictions')).scalar_one()
        handoffs=conn.execute(text('SELECT COUNT(*) FROM predictions WHERE handoff=1')).scalar_one()
        degraded=conn.execute(text("SELECT COUNT(*) FROM predictions WHERE llm_status IN ('degraded','failed')")).scalar_one()
        rows=conn.execute(text('SELECT intent, COUNT(*) n FROM predictions GROUP BY intent ORDER BY n DESC')).mappings().all()
        return {'conversaciones':total,'derivaciones':handoffs,'tasa_derivacion':round(handoffs/total,4) if total else 0,
                'modo_degradado':degraded,'tasa_degradado':round(degraded/total,4) if total else 0,'intenciones':[dict(x) for x in rows]}

def record_attempt(conversation_id: str,failed: bool)->int:
    with engine().begin() as conn:
        row=conn.execute(text('SELECT failed_attempts FROM conversation_state WHERE conversation_id=:id'),{'id':conversation_id}).first()
        count=((row[0] if row else 0)+1) if failed else 0
        conn.execute(text('''INSERT INTO conversation_state(conversation_id,failed_attempts) VALUES(:id,:n)
            ON CONFLICT(conversation_id) DO UPDATE SET failed_attempts=:n'''),{'id':conversation_id,'n':count})
        return count

def append_message(conversation_id: str,message: str,intent: str):
    with engine().begin() as conn:
        conn.execute(text('INSERT INTO conversation_messages(conversation_id,message,intent) VALUES(:c,:m,:i)'),{'c':conversation_id,'m':message,'i':intent})

def get_history(conversation_id: str):
    with engine().begin() as conn:
        rows=conn.execute(text('SELECT message,intent,created_at FROM conversation_messages WHERE conversation_id=:c ORDER BY id'),{'c':conversation_id}).mappings().all()
        return [dict(x) for x in rows]
